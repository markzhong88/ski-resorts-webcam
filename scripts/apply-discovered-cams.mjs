/**
 * Turn verified webcam-discoveries.json into discovered-cams.js
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RESORTS } from '../resorts.js';
import { slugifyMountain } from '../catalog.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

const JUNK_URL =
  /logo|favicon|sprite|icon[-_.]|placeholder|og[-_]?image|banner|overlay|thumbnail|webbutt|webicons|webcam-offline|webcam-preview|live-webcam-bg|safelinks\.protection|\.js(\?|$)|\/js\/hdrelay|untitled-design|b-roll|nav_images|header_1920|headerimage|header\.image|tripcheck\.com/i;

function isJunk(url) {
  const u = String(url || '');
  if (!u.startsWith('http')) return true;
  if (JUNK_URL.test(u)) return true;
  if (/wp-content\/uploads/i.test(u) && !/\/webcam\//i.test(u)) return true;
  if (/wp-content\/themes/i.test(u)) return true;
  if (/still\d{3}/i.test(u)) return true;
  if (/image\d{6}_/.test(u)) return true;
  if (/_\d{2}-\d{2}-\d{2}[_-]/.test(u)) return true;
  if (/XMasTreeTop\d{2}-/.test(u)) return true;
  return false;
}

function youtubeEmbed(url) {
  const raw = String(url);
  const channel = raw.match(/[?&]channel=([A-Za-z0-9_-]+)/);
  if (/live_stream/.test(raw) && channel) {
    return `https://www.youtube.com/embed/live_stream?channel=${channel[1]}&autoplay=1&mute=1&rel=0`;
  }
  const m = raw.match(/(?:embed\/|youtu\.be\/|v=)([A-Za-z0-9_-]{8,})/);
  if (!m || m[1] === 'live_stream') return raw;
  return `https://www.youtube.com/embed/${m[1]}?autoplay=1&mute=1&rel=0`;
}

function preferHttps(url) {
  let out = String(url || '');
  if (out.startsWith('http://')) out = `https://${out.slice(7)}`;
  out = out.replace(/([?&])token=[^&]*/gi, '$1').replace(/\?&/, '?').replace(/[?&]$/, '');
  return out;
}

function camName(mountain, cam, index, total) {
  if (total === 1) return `${mountain} — Live cam`;
  if (cam.provider && cam.provider !== 'Resort') return `${mountain} — ${cam.provider} ${index + 1}`;
  return `${mountain} — Cam ${index + 1}`;
}

const covered = new Set(RESORTS.map((r) => r.mountain));
const raw = JSON.parse(await readFile(path.join(ROOT, 'data', 'webcam-discoveries.json'), 'utf8'));
const cams = [];

for (const row of raw) {
  if (row.status !== 'found' || !row.cams?.length) continue;
  if (covered.has(row.name)) continue;
  const picked = row.cams
    .filter((c) => c.verified && c.url && !isJunk(c.url))
    .map((c) => ({ ...c, url: preferHttps(c.url) }))
    .sort(
      (a, b) =>
        (a.type === 'image' ? 0 : 1) - (b.type === 'image' ? 0 : 1) || (b.score || 0) - (a.score || 0)
    )
    .slice(0, 3);
  picked.forEach((cam, i) => {
    const slug = row.slug || slugifyMountain(row.name);
    const url = cam.provider === 'YouTube' ? youtubeEmbed(cam.url) : cam.url;
    cams.push({
      id: picked.length === 1 ? `${slug}-cam` : `${slug}-cam-${i + 1}`,
      home: i === 0,
      name: camName(row.name, cam, i, picked.length),
      mountain: row.name,
      url,
      type: cam.type,
      region: row.region,
      provider: cam.provider || 'Resort',
      latitude: row.latitude ?? null,
      longitude: row.longitude ?? null,
    });
  });
}

const body = `/** Webcam feeds found from official resort sites. Generated by scripts/apply-discovered-cams.mjs */
export const DISCOVERED_CAMS = ${JSON.stringify(cams, null, 2)};
`;
await writeFile(path.join(ROOT, 'discovered-cams.js'), body);
const mountains = new Set(cams.map((c) => c.mountain));
console.log(`Wrote ${cams.length} cams across ${mountains.size} mountains → discovered-cams.js`);
